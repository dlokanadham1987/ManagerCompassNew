export interface ActionItem {
  text: string;
  done: boolean;
}

export interface DirectReport {
  id: string;
  name: string;
  email: string;
}

export interface PostNote {
  id: string;
  date: string; // yyyy-MM-dd, when this note was added
  text: string;
}

export interface OneOnOneSummaryRequest {
  reportName: string;
  from: string; // yyyy-MM-dd, inclusive
  to: string;
  postNotes: { date: string; text: string }[];
  actionItems: { text: string; done: boolean; meetingDate: string }[];
}

export interface OneOnOneSummaryResponse {
  summary: string;
  periodStart: string;
  periodEnd: string;
  usedModel: boolean;
}

export interface ScheduledMeeting {
  id: string;
  reportId: string;
  reportName: string;
  startsAt: string; // datetime-local value, from the schedule form
  durationMinutes: number;
  preNotes: string[]; // talking points prepared before the conversation
  aiSummary: string | null; // generated by the API (Claude) from the last 2 weeks of notes
  aiSummaryPeriod?: string | null; // e.g. "2026-09-27 to 2026-10-11"
  postNotes: PostNote[]; // appended over time — every save adds a new dated entry, never overwrites
  actionItems: ActionItem[]; // accumulates as post-notes are appended
  nextFollowUpDate: string | null; // most recently set value
  completed: boolean;
}
